import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync, existsSync } from 'node:fs';
import { createApp } from '../server/index.js';
import { DemoService } from '../server/demo.js';
import { createServer } from 'node:http';

const service = new DemoService();
service.records.task[0].assignees = [7, 999];
service.records.task[0].project = [999, 'A current project outside the first page'];
const server = createServer().listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
server.on('request', createApp({ service, authenticate: async () => ({ iss: 'demo', sub: 'demo', scopes: ['odoo:read', 'odoo:write'] }), publicUrl: base, demo: true }));
const executablePath = ['C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', 'C:/Program Files/Google/Chrome/Application/chrome.exe'].find(existsSync);
const browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) });
const errors = [];
let page;
try {
  page = await browser.newPage({ viewport: { width: 1280, height: 960 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/dashboard`);
  await page.getByText('3 tasks · 2 open · 1 done').waitFor();
  assert.equal(await page.locator('body').evaluate(el => el.scrollWidth <= window.innerWidth), true);
  await page.getByRole('button', { name: 'Edit', exact: true }).first().click();
  await page.locator('[name="name"]').fill('Updated title only');
  await page.getByRole('button', { name: 'Review change' }).click();
  assert.equal(await page.locator('#preview-fields tr').count(), 1, 'Unchanged relations must not be submitted');
  await page.getByRole('button', { name: 'Confirm and save' }).click();
  await page.getByText('update saved and verified').waitFor();
  assert.deepEqual(service.records.task[0].assignees, [7, 999]);
  assert.deepEqual(service.records.task[0].project, [999, 'A current project outside the first page']);
  await page.getByRole('button', { name: 'Mark done', exact: true }).first().click();
  await page.getByRole('button', { name: 'Confirm and save' }).click();
  await page.getByText('3 tasks · 1 open · 2 done').waitFor();
  await page.getByRole('button', { name: 'Todos', exact: true }).click();
  await page.getByRole('button', { name: 'Add todo', exact: true }).click();
  await page.locator('[name="name"]').fill('Browser-created todo');
  await page.getByRole('button', { name: 'Review change' }).click();
  assert.equal(service.records.todo.length, 1);
  await page.getByRole('button', { name: 'Confirm and save' }).click();
  await page.getByText('2 todos · 2 open').waitFor();
  assert.equal(service.records.todo.length, 2);
  await page.getByRole('button', { name: 'Projects', exact: true }).click();
  await page.getByRole('button', { name: 'Add project', exact: true }).click();
  await page.locator('[name="name"]').fill('Browser project');
  await page.getByRole('button', { name: 'Review change' }).click();
  await page.getByRole('button', { name: 'Confirm and save' }).click();
  await page.getByText('3 projects · Completion meaning not configured').waitFor();
  await page.getByRole('button', { name: 'Timesheets', exact: true }).click();
  await page.getByRole('button', { name: 'Add timesheet', exact: true }).click();
  await page.locator('[name="name"]').fill('Browser logged work');
  await page.locator('[name="project"]').selectOption('10');
  await page.locator('[name="hours"]').fill('1.25');
  await page.getByRole('button', { name: 'Review change' }).click();
  await page.getByRole('button', { name: 'Confirm and save' }).click();
  await page.getByText('2 timesheets · 4.75 hours logged').waitFor();
  await page.getByRole('button', { name: 'Notes', exact: true }).click();
  await page.getByRole('button', { name: 'Add note', exact: true }).click();
  await page.locator('[name="name"]').fill('Browser note');
  await page.locator('[name="body"]').fill('A private note saved through preview.');
  await page.getByRole('button', { name: 'Review change' }).click();
  await page.getByRole('button', { name: 'Confirm and save' }).click();
  await page.getByText('2 notes', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Tasks', exact: true }).click();
  await page.locator('#records tr').first().waitFor();
  mkdirSync('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true });
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1 });
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto(`${base}/dashboard`); await mobile.locator('#records tr').first().waitFor();
  assert.equal(await mobile.locator('body').evaluate(el => el.scrollWidth <= window.innerWidth), true, 'No page overflow on mobile');
  await mobile.screenshot({ path: 'test-results/dashboard-mobile.png', fullPage: true });
  await mobile.goto(`${base}/setup`); await mobile.locator('#demo-banner:not([hidden])').waitFor();
  assert.equal(await mobile.locator('#connection').isVisible(), false, 'Demo must not ask for real keys');
  assert.deepEqual(errors, []);
  console.log('PASS: desktop/mobile dashboard, five tabs, preview/confirm, completion, create, preserved relations, setup and no browser errors.');
} catch (error) {
  console.error('Browser errors:', errors);
  console.error('Page text:', await page?.locator('body').innerText());
  throw error;
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
